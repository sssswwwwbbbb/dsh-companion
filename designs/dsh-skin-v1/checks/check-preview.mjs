import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
const here=path.dirname(fileURLToPath(import.meta.url)),design=path.resolve(here,'..'),root=path.resolve(here,'../../..');
const modelContext={module:{exports:{}}};
vm.runInNewContext(fs.readFileSync(path.join(design,'preview-model.js'),'utf8'),modelContext);
const model=modelContext.module.exports;
const checks=[];
const check=(name,ok,detail)=>{checks.push({name,passed:!!ok,...(detail?{detail}:{})});if(!ok)throw new Error(name);};
const config=JSON.parse(fs.readFileSync(path.join(design,'content/design-defaults.json')));
check('design defaults explicitly not runtime format',config.kind==='design-intent'&&config.runtimeLoadable===false);
check('every exposed design field has its own valid default',Object.entries(config.controls).every(([k,c])=>Object.hasOwn(c,'default')&&model.same(c.default,config.defaults[k])&&model.valid(c,c.default)));
check('all defaults have declarations',Object.keys(config.defaults).every(k=>Object.hasOwn(config.controls,k)));
for(const name of ['components','screens','app'])new vm.Script(fs.readFileSync(path.join(design,name+'.js'),'utf8'),{filename:name+'.js'});
check('compiled JavaScript parses',true);
const html=fs.readFileSync(path.join(design,'index.html'),'utf8');
const refs=[...html.matchAll(/(?:src|href)="([^"]+)"/g)].map(x=>x[1]).filter(x=>!x.startsWith('data:'));
check('HTML loads only existing local resources',refs.every(x=>!/^https?:/.test(x)&&fs.existsSync(path.join(design,x))));
const source=JSON.parse(fs.readFileSync(path.join(design,'assets/whale-maid/upstream-provenance.json')));
const selected=fs.readdirSync(path.join(design,'assets/whale-maid')).filter(x=>x.endsWith('.webm'));
check('selected videos preserve source bytes',selected.every(f=>{const file=source.files.find(x=>x.name===f.slice(0,-5));return file&&createHash('sha256').update(fs.readFileSync(path.join(design,'assets/whale-maid',f))).digest('hex')===file.sha256;}));
const scan=fs.readFileSync(path.join(design,'assets/reference/whale-girl-scan.mp4'));
const blob=createHash('sha1').update(Buffer.from('blob '+scan.length+'\0')).update(scan).digest('hex');
check('scan matches pinned Git blob',blob==='8848daf137c2e87c258957502c74ae0d87b8a550');
const contrast=JSON.parse(fs.readFileSync(path.join(root,'reports/first-skin/r3-contrast.json')));
check('48 computed text contrast pairs meet chosen 4.5 target',contrast.checks.length===48&&contrast.passed);
const report={date:'2026-11-03',revision:'R3',scope:'local authoring and resource checks, not host acceptance',checks,passed:true,selectedWebm:selected.length,scanNoticeMismatchKnown:true};
fs.writeFileSync(path.join(root,'reports/first-skin/r3-static-validation.json'),JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify({passed:true,checks:checks.length}));
